"""Target audit and construction.

The binary label comes straight from the ``filter_status`` column produced by
the thesis's multi-criteria rule. The legacy ``EnhancedTargetCreator`` is
retired: its resistance-threshold path re-derived the label from the same
signals used as features (circular), and its fallback silently labeled the
last 20% of rows as clogged.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)


def make_binary_target(df: pd.DataFrame) -> np.ndarray:
    """1 = Clogged, 0 = Not Clogged, straight from filter_status."""
    return (df["filter_status"] == "Clogged").to_numpy(dtype=np.int8)


def make_horizon_target(y: np.ndarray, h_rows: int) -> np.ndarray:
    """Early-warning target: y_H[t] = y[t + h]. Last h entries are -1
    (undefined; caller must drop them from any modeling set)."""
    if h_rows == 0:
        return y.copy()
    out = np.full_like(y, -1)
    out[:-h_rows] = y[h_rows:]
    return out


def audit_labels(df: pd.DataFrame, out_path: str | Path | None = None) -> dict:
    """Verify label provenance facts and archive them.

    Checks: single healthy->clogged transition; its location; class balance;
    empirical relationship between validation_score (the rule's 0-20 point
    score as stored) and the binary label.
    """
    y = make_binary_target(df)
    changes = np.flatnonzero(np.diff(y) != 0)
    transitions = [int(i) + 2 for i in changes]  # 1-based row of first changed sample

    score = df["validation_score"]
    clogged_scores = score[y == 1]
    healthy_scores = score[y == 0]

    audit = {
        "n_rows": int(len(df)),
        "n_transitions": int(len(transitions)),
        "transition_rows_1based": transitions,
        "n_healthy": int((y == 0).sum()),
        "n_clogged": int((y == 1).sum()),
        "clogged_fraction": round(float(y.mean()), 4),
        "validation_score_range": [int(score.min()), int(score.max())],
        "min_score_when_clogged": int(clogged_scores.min()),
        "max_score_when_healthy": int(healthy_scores.max()),
        "score_separates_label": bool(clogged_scores.min() > healthy_scores.max()),
        # thesis text states clogged iff score >= 12, but the stored data uses
        # >= 11 (2,549 clogged rows carry score 11) — a documented discrepancy
        # the paper must reconcile.
        "empirical_clogged_threshold": int(clogged_scores.min()),
        "note": (
            "filter_status is generated by the thesis's 7-criterion rule "
            "(clogged if score >= 12 of max 20); validation_score is that "
            "score. Any model given validation_score (or the rule's other "
            "inputs: adaptive_cusum, short/long EMA, cusum_threshold) as a "
            "feature merely re-implements the rule -> excluded in "
            "leakage-free mode."
        ),
    }
    if len(transitions) != 1:
        logger.warning("expected exactly 1 label transition, found %d", len(transitions))

    if out_path is not None:
        Path(out_path).parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as fh:
            json.dump(audit, fh, indent=2)
        logger.info("label audit written to %s", out_path)
    return audit
